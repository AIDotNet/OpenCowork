#!/usr/bin/env node
/* eslint-disable @typescript-eslint/explicit-function-return-type */
// Generates the TS + C# worker IPC contracts from the single model at
// src/shared/worker-contracts/model.ts. Usage:
//   node scripts/generate-worker-contracts.mjs          # write outputs
//   node scripts/generate-worker-contracts.mjs --check  # fail if outputs are stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MODEL_PATH = resolve(root, 'src/shared/worker-contracts/model.ts')
const TS_OUT_PATH = resolve(root, 'src/shared/worker-contracts/generated/contracts.ts')
const CS_OUT_PATH = resolve(
  root,
  'sidecars/OpenCowork.Native.Worker/Generated/WorkerContracts.g.cs'
)
const HEADER =
  'GENERATED by scripts/generate-worker-contracts.mjs from src/shared/worker-contracts/model.ts — do not edit.'

const checkMode = process.argv.includes('--check')

// ---------- parse model ----------

const sourceText = readFileSync(MODEL_PATH, 'utf8')
const source = ts.createSourceFile(MODEL_PATH, sourceText, ts.ScriptTarget.ES2022, true)

/** @type {Array<{ name: string, value: number, doc: string | null }>} */
const constants = []
/** @type {Array<{ name: string, doc: string | null, fields: Array<{ name: string, tsType: string, csType: string, doc: string | null }> }>} */
const dtos = []
/** @type {Array<{ method: string, params: string, result: string }>} */
const methods = []

function fail(message, node) {
  const pos = node ? source.getLineAndCharacterOfPosition(node.getStart()) : null
  const where = pos ? ` (model.ts:${pos.line + 1}:${pos.character + 1})` : ''
  console.error(`[contracts:gen] ${message}${where}`)
  process.exit(1)
}

function jsDocText(node) {
  const docs = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc)
  if (docs.length === 0) return null
  const text = docs
    .map((doc) => (typeof doc.comment === 'string' ? doc.comment : ''))
    .join(' ')
    .replaceAll(/\s+/g, ' ')
    .trim()
  return text || null
}

function csTagOf(node) {
  for (const tag of ts.getJSDocTags(node)) {
    if (tag.tagName.text !== 'cs') continue
    const value = typeof tag.comment === 'string' ? tag.comment.trim() : ''
    if (value !== 'int' && value !== 'long')
      fail(`@cs tag must be "int" or "long", got "${value}"`, node)
    return value
  }
  return null
}

/** Maps a model field type node to { ts, cs }. */
function mapType(typeNode, csNumber) {
  if (!typeNode) fail('field is missing a type', typeNode)
  switch (typeNode.kind) {
    case ts.SyntaxKind.BooleanKeyword:
      return { ts: 'boolean', cs: 'bool' }
    case ts.SyntaxKind.NumberKeyword:
      return { ts: 'number', cs: csNumber ?? 'double' }
    case ts.SyntaxKind.StringKeyword:
      return { ts: 'string', cs: 'string' }
    default:
      break
  }
  if (ts.isArrayTypeNode(typeNode)) {
    const element = mapType(typeNode.elementType, csNumber)
    return { ts: `${element.ts}[]`, cs: `${element.cs}[]` }
  }
  if (ts.isUnionTypeNode(typeNode)) {
    const parts = typeNode.types
    const nullParts = parts.filter(
      (part) => ts.isLiteralTypeNode(part) && part.literal.kind === ts.SyntaxKind.NullKeyword
    )
    const valueParts = parts.filter((part) => !nullParts.includes(part))
    if (nullParts.length !== 1 || valueParts.length !== 1) {
      fail('unions must have exactly the form `T | null`', typeNode)
    }
    const inner = mapType(valueParts[0], csNumber)
    return { ts: `${inner.ts} | null`, cs: `${inner.cs}?` }
  }
  if (ts.isTypeReferenceNode(typeNode)) {
    const name = typeNode.typeName.getText()
    return { ts: name, cs: name }
  }
  fail(`unsupported field type: ${typeNode.getText()}`, typeNode)
  return { ts: '', cs: '' }
}

function parseWorkerMethods(decl) {
  for (const member of decl.members) {
    if (!ts.isPropertySignature(member) || !member.name || !ts.isStringLiteral(member.name)) {
      fail('WorkerMethods entries must be string-literal keys', member)
    }
    const type = member.type
    if (!type || !ts.isTypeLiteralNode(type))
      fail('WorkerMethods values must be { params; result } literals', member)
    let params = null
    let result = null
    for (const prop of type.members) {
      if (!ts.isPropertySignature(prop) || !prop.name) continue
      const key = prop.name.getText()
      const text = prop.type?.getText() ?? ''
      if (key === 'params') params = text
      if (key === 'result') result = text
    }
    if (!params || !result) fail('WorkerMethods entries need both params and result', member)
    methods.push({ method: member.name.text, params, result })
  }
}

for (const statement of source.statements) {
  if (ts.isVariableStatement(statement)) {
    const decl = statement.declarationList.declarations[0]
    if (decl?.name.getText() !== 'constants') continue
    let objectLiteral = decl.initializer
    if (objectLiteral && ts.isAsExpression(objectLiteral)) objectLiteral = objectLiteral.expression
    if (!objectLiteral || !ts.isObjectLiteralExpression(objectLiteral)) {
      fail('constants must be an object literal', decl)
    }
    for (const prop of objectLiteral.properties) {
      if (!ts.isPropertyAssignment(prop)) fail('constants entries must be plain assignments', prop)
      if (!ts.isNumericLiteral(prop.initializer))
        fail('constants values must be integer literals', prop)
      constants.push({
        name: prop.name.getText(),
        value: Number(prop.initializer.text),
        doc: jsDocText(prop)
      })
    }
    continue
  }
  if (!ts.isInterfaceDeclaration(statement)) continue
  if (statement.name.text === 'WorkerMethods') {
    parseWorkerMethods(statement)
    continue
  }
  const fields = []
  for (const member of statement.members) {
    if (!ts.isPropertySignature(member) || !member.name)
      fail('DTO members must be property signatures', member)
    if (member.questionToken) fail('optional fields are not allowed; use `T | null`', member)
    const mapped = mapType(member.type, csTagOf(member))
    fields.push({
      name: member.name.getText(),
      tsType: mapped.ts,
      csType: mapped.cs,
      doc: jsDocText(member)
    })
  }
  dtos.push({ name: statement.name.text, doc: jsDocText(statement), fields })
}

if (constants.length === 0 || dtos.length === 0 || methods.length === 0) {
  fail('model must define constants, at least one DTO, and WorkerMethods')
}

// ---------- emit TypeScript ----------

function emitTs() {
  const lines = [`// ${HEADER}`, '']
  for (const constant of constants) {
    if (constant.doc) lines.push(`/** ${constant.doc} */`)
    lines.push(`export const ${constant.name} = ${constant.value} as const`)
  }
  lines.push('')
  for (const dto of dtos) {
    if (dto.doc) lines.push(`/** ${dto.doc} */`)
    lines.push(`export interface ${dto.name} {`)
    for (const field of dto.fields) {
      if (field.doc) lines.push(`  /** ${field.doc} */`)
      lines.push(`  ${field.name}: ${field.tsType}`)
    }
    lines.push('}', '')
  }
  lines.push('export interface WorkerMethodMap {')
  for (const entry of methods) {
    lines.push(`  '${entry.method}': { params: ${entry.params}; result: ${entry.result} }`)
  }
  lines.push('}', '')
  lines.push('export type WorkerMethodName = keyof WorkerMethodMap')
  lines.push('')
  return lines.join('\n')
}

// ---------- emit C# ----------

function pascalCase(name) {
  return name.charAt(0).toUpperCase() + name.slice(1)
}

function pascalConstName(name) {
  return name
    .toLowerCase()
    .split('_')
    .map((part) => pascalCase(part))
    .join('')
}

function emitCs() {
  const lines = [
    `// ${HEADER}`,
    // .g.cs files are exempt from the project-wide nullable context; declare it.
    '#nullable enable',
    'using System.Text.Json.Serialization;',
    '',
    'namespace OpenCowork.Contracts.Generated;',
    ''
  ]
  lines.push('public static class WorkerContractConstants', '{')
  for (const constant of constants) {
    if (constant.doc) lines.push(`    /// <summary>${constant.doc}</summary>`)
    lines.push(`    public const int ${pascalConstName(constant.name)} = ${constant.value};`)
  }
  lines.push('}', '')
  for (const dto of dtos) {
    if (dto.doc) lines.push(`/// <summary>${dto.doc}</summary>`)
    const args = dto.fields.map((field) => `${field.csType} ${pascalCase(field.name)}`).join(', ')
    lines.push(`public sealed record ${dto.name}(${args});`, '')
  }
  lines.push(
    '// AOT-safe serializer context for the generated DTOs (mirrors WorkerJsonContext options).',
    '[JsonSourceGenerationOptions(',
    '    GenerationMode = JsonSourceGenerationMode.Metadata,',
    '    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,',
    '    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull)]'
  )
  for (const dto of dtos) {
    lines.push(`[JsonSerializable(typeof(${dto.name}))]`)
  }
  lines.push('public sealed partial class GeneratedContractsJsonContext : JsonSerializerContext;')
  lines.push('')
  return lines.join('\n')
}

// ---------- write / check ----------

const outputs = [
  { path: TS_OUT_PATH, content: emitTs() },
  { path: CS_OUT_PATH, content: emitCs() }
]

let stale = false
for (const output of outputs) {
  const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : null
  if (current === output.content) continue
  stale = true
  if (checkMode) {
    console.error(`[contracts:gen] stale: ${output.path}`)
    continue
  }
  mkdirSync(dirname(output.path), { recursive: true })
  writeFileSync(output.path, output.content, 'utf8')
  console.log(`[contracts:gen] wrote ${output.path}`)
}

if (checkMode && stale) {
  console.error('[contracts:gen] outputs are out of date — run `npm run contracts:gen`')
  process.exit(1)
}
if (!stale) {
  console.log('[contracts:gen] outputs up to date')
}
