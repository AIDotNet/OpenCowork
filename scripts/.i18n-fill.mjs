function setDeep(obj, key, value) {
  const parts = key.split('.')
  let node = obj
  for (let i = 0; i < parts.length - 1; i += 1) {
    const part = parts[i]
    if (typeof node[part] !== 'object' || node[part] === null) node[part] = {}
    node = node[part]
  }
  const leaf = parts[parts.length - 1]
  if (typeof node[leaf] === 'string') return false
  node[leaf] = value
  return true
}

for (const [locale, entries] of Object.entries(T)) {
  const file = path.join(LOCALES_DIR, locale, 'settings.json')
  const json = JSON.parse(fs.readFileSync(file, 'utf8'))
  let added = 0
  for (const [key, value] of Object.entries(entries)) {
    if (setDeep(json, key, value)) added += 1
  }
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n')
  console.log(`${locale}: +${added}`)
}
