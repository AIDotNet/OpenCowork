#!/usr/bin/env node
/* eslint-disable @typescript-eslint/explicit-function-return-type */
// Generates TS + C# contracts from:
//   src/shared/worker-contracts/model.ts
//   src/shared/runtime-contracts/model.ts
// Usage:
//   node scripts/generate-worker-contracts.mjs          # write outputs
//   node scripts/generate-worker-contracts.mjs --check  # fail if outputs are stale
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import {
  ContractModelError,
  emitRuntimeCSharp,
  emitRuntimeIpc,
  emitRuntimeTypeScript,
  emitWorkerCSharp,
  emitWorkerTypeScript,
  parseContractModel
} from './lib/contract-model.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkMode = process.argv.includes('--check')

const workerModelPath = resolve(root, 'src/shared/worker-contracts/model.ts')
const runtimeModelPath = resolve(root, 'src/shared/runtime-contracts/model.ts')

const WORKER_HEADER =
  'GENERATED by scripts/generate-worker-contracts.mjs from src/shared/worker-contracts/model.ts — do not edit.'
const RUNTIME_HEADER =
  'GENERATED by scripts/generate-worker-contracts.mjs from src/shared/runtime-contracts/model.ts — do not edit.'

function readModel(path) {
  return parseContractModel(readFileSync(path, 'utf8'), path)
}

function writeOrCheck(path, content) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === content) return false
  if (checkMode) {
    console.error(`[contracts:gen] stale: ${path}`)
    return true
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content, 'utf8')
  console.log(`[contracts:gen] wrote ${path}`)
  return true
}

try {
  const workerModel = readModel(workerModelPath)
  if (workerModel.constants.length === 0 || workerModel.dtos.length === 0) {
    throw new ContractModelError('worker model must define constants and at least one DTO')
  }
  if (!workerModel.maps.some((map) => map.name === 'WorkerMethods')) {
    throw new ContractModelError('worker model must define WorkerMethods')
  }

  const runtimeModel = readModel(runtimeModelPath)
  if (!runtimeModel.maps.some((map) => map.name === 'RuntimeCommands')) {
    throw new ContractModelError('runtime model must define RuntimeCommands')
  }
  if (!runtimeModel.maps.some((map) => map.name === 'RuntimeQueries')) {
    throw new ContractModelError('runtime model must define RuntimeQueries')
  }
  if (!runtimeModel.maps.some((map) => map.name === 'RuntimeEvents')) {
    throw new ContractModelError('runtime model must define RuntimeEvents')
  }
  if (!runtimeModel.maps.some((map) => map.name === 'UiCapabilities')) {
    throw new ContractModelError('runtime model must define UiCapabilities')
  }

  const outputs = [
    {
      path: resolve(root, 'src/shared/worker-contracts/generated/contracts.ts'),
      content: emitWorkerTypeScript(workerModel, WORKER_HEADER)
    },
    {
      path: resolve(root, 'sidecars/OpenCowork.Native.Worker/Generated/WorkerContracts.g.cs'),
      content: emitWorkerCSharp(workerModel, WORKER_HEADER)
    },
    {
      path: resolve(root, 'src/shared/runtime-contracts/generated/contracts.ts'),
      content: emitRuntimeTypeScript(runtimeModel, RUNTIME_HEADER)
    },
    {
      path: resolve(root, 'src/shared/runtime-contracts/generated/ipc.ts'),
      content: emitRuntimeIpc(runtimeModel, RUNTIME_HEADER)
    },
    {
      path: resolve(root, 'sidecars/OpenCowork.Native.Worker/Generated/AgentRuntimeContracts.g.cs'),
      content: emitRuntimeCSharp(runtimeModel, RUNTIME_HEADER)
    }
  ]

  let stale = false
  for (const output of outputs) {
    if (writeOrCheck(output.path, output.content)) stale = true
  }

  const sync = spawnSync(
    process.execPath,
    [resolve(root, 'cli/scripts/sync-shared.mjs'), ...(checkMode ? ['--check'] : [])],
    { cwd: root, stdio: 'inherit' }
  )
  if (sync.status !== 0) process.exit(sync.status ?? 1)

  if (checkMode && stale) {
    console.error('[contracts:gen] outputs are out of date — run `npm run contracts:gen`')
    process.exit(1)
  }
  if (!stale) {
    console.log('[contracts:gen] outputs up to date')
  }
} catch (error) {
  const message = error instanceof Error ? error.message : String(error)
  console.error(`[contracts:gen] ${message}`)
  process.exit(1)
}
